const pick = (table: Record<string, string[]>, language: string): string[] => table[language] || table.en;

/** Full month name, month = 1..12. */
export const monthName = (month: number, language: string): string => pick(FULL, language)[(month - 1 + 12) % 12];

/** Short month name for chart axes / compact lists, month = 1..12. */
export const monthShort = (month: number, language: string): string => pick(SHORT, language)[(month - 1 + 12) % 12];

/** "September 2026" / "Сентябрь 2026" / "2026年9月" (month = 1..12). */
export const formatMonthYear = (year: number, month: number, language: string): string =>
  language === 'zh' ? `${year}年${month}月` : `${monthName(month, language)} ${year}`;
