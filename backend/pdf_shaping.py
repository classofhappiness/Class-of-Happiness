class ShapedString(Group):
    """Group of single-glyph Strings usable inside a reportlab.graphics Drawing.
    anchor: 'start' | 'middle' | 'end'.  Literal left/middle/right semantics unless rtl=True, in which case
    'start' puts the text's RIGHT edge at x and 'end' puts its LEFT edge at x.  .width is the text width."""

    def __init__(self, x, y, text, fontName, fontSize=10, anchor="start", fillColor=colors.black, rtl=False,
                 textAnchor=None):
        Group.__init__(self)
        anchor = textAnchor or anchor
        text = " ".join(str(text).split("\n"))
        lg = lang_for_font(fontName)
        if lg is None or lg not in _READY:
            # not a shaped font (or engine not ready): plain String with literal anchor semantics
            object.__setattr__(self, "width", pdfmetrics.stringWidth(text, fontName, fontSize) if fontName in pdfmetrics.getRegisteredFontNames() else 0)
            eff = {"start": "end" if rtl else "start", "end": "start" if rtl else "end"}.get(anchor, anchor)
            self.add(String(x, y, text, fontName=fontName, fontSize=fontSize, fillColor=fillColor, textAnchor=eff))
            return
        bold = "bold" in (fontName or "").lower()
        chars = [(c, bold, fillColor, float(fontSize), None) for c in text]
        levels = bidi_levels(text, 1 if lg == "ar" else 0)
        runs = _reorder(_make_runs(chars, levels, 0, len(chars), lg))
        w = sum(it.width for _, it in runs)
        object.__setattr__(self, "width", w)  # Group validates attribute names
        if anchor == "middle":
            x0 = x - w / 2.0
        elif anchor == "start":
            x0 = x - w if rtl else x
        else:  # 'end'
            x0 = x if rtl else x - w
        cx = x0
        for _, it in runs:
            f = it.face
            sc = it.size / f.upem
            for gid, adv, xo, yo in it.glyphs:
                if gid:
                    self.add(String(cx + xo * sc, y + yo * sc, chr(PUA0 + gid), fontName=f.rlname,
                                    fontSize=it.size, fillColor=fillColor))
                cx += adv * sc


def shaped_string(x, y, text, fontName, fontSize=10, anchor="start", fillColor=colors.black, rtl=False):
    return ShapedString(x, y, text, fontName, fontSize, anchor, fillColor, rtl)


