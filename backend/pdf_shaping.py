_SWAP_NAMES = {"LINEBEFORE": "LINEAFTER", "LINEAFTER": "LINEBEFORE",
               "LEFTPADDING": "RIGHTPADDING", "RIGHTPADDING": "LEFTPADDING"}
_SWAP_LR = {"LEFT": "RIGHT", "RIGHT": "LEFT"}


def _mirror_cmds(cmds, ncols):
    out = []
    for cmd in cmds:
        if len(cmd) < 3 or not isinstance(cmd[1], (tuple, list)) or not isinstance(cmd[2], (tuple, list)):
            out.append(cmd)
            continue
        name = cmd[0]
        (c0, r0), (c1, r1) = cmd[1], cmd[2]
        if isinstance(c0, str) or isinstance(c1, str):
            out.append(cmd)
            continue
        a = c0 + ncols if c0 < 0 else c0
        b = c1 + ncols if c1 < 0 else c1
        a, b = min(a, b), max(a, b)
        na, nb = ncols - 1 - b, ncols - 1 - a
        rest = list(cmd[3:])
        if name in ("ALIGN", "ALIGNMENT") and rest and isinstance(rest[0], str):
            rest[0] = _SWAP_LR.get(rest[0].upper(), rest[0])
        elif name == "COLBACKGROUNDS" and rest and rest[0]:
            cl = list(rest[0])
            rest[0] = [cl[(ncols - 1 - j - a) % len(cl)] for j in range(na, nb + 1)]
        name = _SWAP_NAMES.get(name, name)
        out.append((name, (na, r0), (nb, r1)) + tuple(rest))
    return out


class ShapedTable(Table):
    """reportlab Table that, for Arabic documents (get_lang()=='ar'), is mirrored (cell order, colWidths, style
    columns, ALIGN LEFT<->RIGHT, LINEBEFORE<->LINEAFTER, LEFT/RIGHTPADDING, hAlign) and, for hi/ar, converts
    plain string/number cells whose FONTNAME is a shaped font into ShapedParagraphs.  Cells with no ALIGN
    command are start-aligned (right in a mirrored table).  Behaves exactly like Table for other languages."""

    def __init__(self, data, colWidths=None, rowHeights=None, style=None, *args, **kw):
        self._coh_mirror = False
        self._coh_done = False
        lg = get_lang()
        if lg == "ar" and not kw.get("normalizedData") and isinstance(data, (list, tuple)) and data:
            self._coh_mirror = True
            n = max(len(r) for r in data)
            data = [(list(r) + [""] * (n - len(r)))[::-1] for r in data]
            if isinstance(colWidths, (list, tuple)):
                colWidths = list(colWidths)[::-1]
            if kw.get("hAlign") in _SWAP_LR:
                kw["hAlign"] = _SWAP_LR[kw["hAlign"]]
            default = ("ALIGN", (0, 0), (-1, -1), "LEFT")  # mirrored to RIGHT: start edge in a mirrored table
            if isinstance(style, TableStyle):
                ns = TableStyle([default] + list(style.getCommands()))
                ns._opts = dict(getattr(style, "_opts", {}))
                for a in ("spaceBefore", "spaceAfter"):
                    if hasattr(style, a):
                        setattr(ns, a, getattr(style, a))
                style = ns
            else:
                style = TableStyle([default] + list(style or []))
        Table.__init__(self, data, colWidths, rowHeights, style, *args, **kw)

    def setStyle(self, tblstyle):
        if getattr(self, "_coh_mirror", False):
            if not isinstance(tblstyle, TableStyle):
                tblstyle = TableStyle(tblstyle)
            ns = TableStyle(_mirror_cmds(tblstyle.getCommands(), self._ncols))
            ns._opts = dict(getattr(tblstyle, "_opts", {}))
            for a in ("spaceBefore", "spaceAfter"):
                if hasattr(tblstyle, a):
                    setattr(ns, a, getattr(tblstyle, a))
            for cmd in ns.getCommands():  # a SPAN's content cell must be its left-most cell after mirroring
                if cmd[0] == "SPAN" and len(cmd) >= 3:
                    (c0, r0), (c1, r1) = cmd[1], cmd[2]
                    r0 = r0 + self._nrows if isinstance(r0, int) and r0 < 0 else r0
                    c0 = c0 + self._ncols if c0 < 0 else c0
                    c1 = c1 + self._ncols if c1 < 0 else c1
                    if isinstance(r0, int) and 0 <= r0 < self._nrows and c0 != c1:
                        row = self._cellvalues[r0]
                        if not isinstance(row, list):
                            row = self._cellvalues[r0] = list(row)
                        row[c0], row[c1] = row[c1], row[c0]
            tblstyle = ns
        Table.setStyle(self, tblstyle)

    def _shape_cells(self):
        self._coh_done = True
        for r, row in enumerate(self._cellvalues):
            for c, v in enumerate(row):
                if isinstance(v, bool) or not isinstance(v, (str, int, float)) or str(v) == "":
                    continue
                cs = self._cellStyles[r][c]
                lg = lang_for_font(cs.fontname)
                if not lg or lg not in _READY:
                    continue
                if not isinstance(row, list):
                    row = self._cellvalues[r] = list(row)
                fs = cs.fontsize
                lead = max(cs.leading or 0, fs * (1.4 if lg == "hi" else 1.25))
                al = (cs.alignment or "LEFT").upper()
                if al == "CENTRE":
                    al = "CENTER"
                if lg == "ar" and al in _SWAP_LR:
                    al = _SWAP_LR[al]  # physical -> logical (TA_LEFT is the start edge)
                ta = {"LEFT": TA_LEFT, "CENTER": TA_CENTER, "RIGHT": TA_RIGHT}.get(al, TA_LEFT)
                ps = ParagraphStyle("coh-cell", fontName=cs.fontname, fontSize=fs, leading=lead,
                                    textColor=cs.color, alignment=ta)
                markup = _escape(str(v), quote=False).replace("\n", "<br/>")
                try:
                    row[c] = ShapedParagraph(markup, ps, lg)
                except Exception as e:  # pragma: no cover
                    _log.warning("pdf_shaping: table cell not shaped: %s", e)

    def _calc(self, availWidth, availHeight):
        if not self._coh_done:
            self._shape_cells()
        return Table._calc(self, availWidth, availHeight)
