"""HarfBuzz-shaped text for ReportLab PDFs: Hindi (Devanagari) and Arabic.

ReportLab cannot shape complex scripts (no GSUB/GPOS, no bidi).  This module shapes text with HarfBuzz
(uharfbuzz) and draws it glyph by glyph through "private use" copies of the fonts (cmap U+E000+gid -> gid,
generated by backend/fonts/build_pua_fonts.py and committed under backend/fonts/pua/), so the PDF still contains
a normal embedded, subset TrueType font and real vector text.

Pure module: needs only reportlab and (optionally) uharfbuzz.  If uharfbuzz is missing, AVAILABLE is False,
init() returns an empty set and make_paragraph() returns ordinary reportlab Paragraphs.  Nothing here raises at
import time.

Public API
    AVAILABLE, init(font_dir) -> set of ready language codes ({'hi','ar'} subset)
    SHAPED_FONT_NAMES, lang_for_font(name)
    set_lang(lang) / get_lang()                (ContextVar; the PDF generator sets it first)
    ShapedParagraph(text, style, lang=None)    (Flowable, Paragraph look-alike)
    ShapedString / shaped_string(...)          (graphics Group for chart labels)
    ShapedTable(Table)                         (mirrors tables for Arabic, shapes string cells for hi/ar)
    make_paragraph(text, style, lang_hint=None)

Bidi: own implementation of the needed subset of UAX #9 (no explicit embeddings/isolates), base direction RTL
for Arabic and LTR for Hindi, per-line L2 reordering.  Known behaviour (correct UAX #9, same as browsers): a colon
after a Latin word inside an RTL paragraph ('Anna: 12') displays as '12 :Anna'.  Translators should avoid
'<Latin>:' in Arabic strings, or add U+200F (RLM) after the colon.
"""
