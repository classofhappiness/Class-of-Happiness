_NAME_TO_CODE = {n.lower(): c for c, n in ISO_COUNTRIES.items()}
_NAME_TO_CODE.update({k: c for k, c in _ALIASES.items() if c in ISO_COUNTRIES})


def country_name(code):
    return ISO_COUNTRIES.get((code or "").strip().upper())


def country_code_from_value(value):
    """ISO-2 code for an ISO code or an English country name (any case); None for empty/unknown/declined."""
    v = (value or "").strip()
    if not v:
        return None
    hit = _NAME_TO_CODE.get(v.lower())
    if hit:
        return hit
    if len(v) == 2:
        up = v.upper()
        return up if up in ISO_COUNTRIES else None
    return None
